import asyncio, json, os
from playwright.async_api import async_playwright
OFF='file://'+os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),'dist-offline','Lingoa de Iapam.html').replace(' ','%20')
async def main():
    async with async_playwright() as p:
        b=await p.chromium.launch()
        # ---- PWA
        ctx=await b.new_context(viewport={'width':820,'height':1180},device_scale_factor=1)  # iPad-ish portrait
        pg=await ctx.new_page(); errs=[]
        pg.on('pageerror',lambda e: errs.append('PAGEERROR '+str(e)))
        pg.on('console',lambda m: errs.append(m.text) if m.type=='error' else None)
        await pg.goto('http://localhost:8766/'); 
        await pg.wait_for_function("navigator.serviceWorker && navigator.serviceWorker.ready.then(()=>true)")
        await pg.wait_for_timeout(2500)
        await pg.reload(); await pg.wait_for_timeout(1200)
        ctrl=await pg.evaluate("!!navigator.serviceWorker.controller")
        cached=await pg.evaluate("caches.keys().then(async ks=>{const c=await caches.open(ks[0]);return (await c.keys()).length})")
        print('PWA controlled:',ctrl,'cached entries:',cached)
        await ctx.set_offline(True)
        await pg.reload(); await pg.wait_for_timeout(1500)
        title=await pg.title(); h1=await pg.locator('h1').first.inner_text()
        fonts=await pg.evaluate("document.fonts.ready.then(()=>[...document.fonts].filter(f=>f.status==='loaded').map(f=>f.family+' '+f.weight))")
        await pg.evaluate("Audio_.load('f')"); await pg.wait_for_timeout(500)
        au=await pg.evaluate("Audio_.data.f ? Object.keys(Audio_.data.f).length : 0")
        print('OFFLINE reload ->',title,'|',h1,'| fonts loaded:',fonts,'| audio clips:',au, '| env', await pg.evaluate('ENV'))
        await pg.screenshot(path='shots/40_pwa_offline_today.png')
        # do lesson 1 offline quickly via UI
        await pg.click('text=Skip for now'); await pg.click('text=Start lesson'); await pg.click('.ov-foot >> text=Start'); await pg.wait_for_timeout(300)
        await pg.screenshot(path='shots/41_pwa_offline_meet.png')
        await pg.click('.ov-head .iconbtn')
        await pg.evaluate("for (const id of ['h:あ','h:い','h:う']) { introduce(id); rate(id+'|r', Rating.Good, 2000); rate(id+'|l', Rating.Good, 2000); } save(); render();")
        await pg.click('.tab[data-tab=more]:visible'); await pg.click('text=Settings'); await pg.wait_for_timeout(800)
        await pg.screenshot(path='shots/42_pwa_settings.png', full_page=True)
        await pg.click('text=Show code'); code_pwa=await pg.locator('#s-code-out').input_value()
        print('PWA code prefix',code_pwa[:5],'len',len(code_pwa))
        print('PWA errors',[e for e in errs if 'ERR_INTERNET_DISCONNECTED' not in e])
        await ctx.close()
        # ---- Claude version (with mock account) restores the PWA code, then exports
        MOCK="""window.__dbstore={};window.claude={use:async(n)=>{await new Promise(r=>setTimeout(r,100)); if(n==='user')return{id:async()=>'u1'}; if(n==='db')return{doc:(p)=>({get:async()=>({exists:p in window.__dbstore,data:()=>window.__dbstore[p],metadata:{}}),set:async(d)=>{window.__dbstore[p]=d},onSnapshot:()=>()=>{}})}; return null;}};"""
        ctx=await b.new_context(viewport={'width':390,'height':844}); await ctx.add_init_script(MOCK)
        pg=await ctx.new_page(); errs=[]; pg.on('pageerror',lambda e: errs.append(str(e)))
        await pg.goto('http://localhost:8765/test.html'); await pg.wait_for_timeout(800)
        await pg.evaluate("for (const id of ['h:か','h:き']) { introduce(id); rate(id+'|r', Rating.Good, 2000); } save();")
        legacy=await pg.evaluate("btoa(unescape(encodeURIComponent(JSON.stringify(S))))")
        await pg.click('.tab[data-tab=more]:visible'); await pg.click('text=Settings'); await pg.wait_for_timeout(500)
        await pg.fill('#s-code', code_pwa); await pg.click('text=Restore and merge'); await pg.wait_for_timeout(600)
        n=await pg.evaluate("Object.keys(S.intro).sort().join(' ')"); print('Claude after restoring PWA code:',n)
        await pg.click('.tab[data-tab=more]:visible'); await pg.click('text=Settings'); await pg.wait_for_timeout(500)
        await pg.screenshot(path='shots/43_claude_settings.png', full_page=True)
        await pg.click('text=Show code'); code_cl=await pg.locator('#s-code-out').input_value()
        print('Claude errors',errs)
        await ctx.close()
        # ---- single file: restore Claude code + legacy code
        ctx=await b.new_context(viewport={'width':1280,'height':860})
        pg=await ctx.new_page(); errs=[]; pg.on('pageerror',lambda e: errs.append(str(e))); pg.on('console',lambda m: errs.append(m.text) if m.type=='error' else None)
        await pg.goto(OFF); await pg.wait_for_timeout(1200)
        fonts=await pg.evaluate("document.fonts.ready.then(()=>[...document.fonts].filter(f=>f.status==='loaded').map(f=>f.family))")
        au=await pg.evaluate("Audio_.load('m').then(()=>Object.keys(Audio_.data.m).length)")
        print('FILE version: env',await pg.evaluate('ENV'),'fonts',fonts,'audio',au)
        await pg.click('.tab[data-tab=more]:visible'); await pg.click('text=Settings'); await pg.wait_for_timeout(400)
        await pg.fill('#s-code', code_cl); await pg.click('text=Restore and merge'); await pg.wait_for_timeout(500)
        print('FILE after restoring Claude code:', await pg.evaluate("Object.keys(S.intro).sort().join(' ')"))
        await pg.click('.tab[data-tab=more]:visible'); await pg.click('text=Settings'); await pg.wait_for_timeout(300)
        await pg.fill('#s-code', legacy); await pg.click('text=Restore and merge'); await pg.wait_for_timeout(500)
        print('FILE after legacy code ok:', await pg.evaluate("Object.keys(S.intro).length"))
        await pg.click('.tab[data-tab=more]:visible'); await pg.click('text=Settings'); await pg.wait_for_timeout(300)
        await pg.fill('#s-code', 'nonsense'); await pg.click('text=Restore and merge'); await pg.wait_for_timeout(300)
        print('bad code toast:', await pg.locator('.toast').last.inner_text())
        await pg.reload(); await pg.wait_for_timeout(800)
        print('FILE persisted after reload:', await pg.evaluate("Object.keys(S.intro).length"))
        await pg.screenshot(path='shots/44_file_today.png')
        print('FILE errors',errs)
        await b.close()
asyncio.run(main())
